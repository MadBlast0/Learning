# A string is text written inside quotation marks

name = "Alex"
print(name)

# A variable can be changed

name = "Sam"
print(name)

# Strings can be joined together

first_name = "Alex"
last_name = "William"
full_name = first_name + " " + last_name
print(full_name)

# str() converts a value into a string

age = 25
age_as_text = str(age)
print(age_as_text)