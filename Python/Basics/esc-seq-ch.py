# New lines in Python can be created using the
#  escape sequence  "  \n  ""
# . The following code demonstrates
#  how to use this escape sequence to create new lines
#  in a string.
print("Hello, World!\nHow are you?")


#for quotes insie quotes  "   \"    " 
print("He said, \"Hello!\"")


#similarly for single quotes inside single quotes  '   \'    '
print('It\'s a beautiful day!')


# and also for backslash  "   \\    "
print("This is a backslash: \\")    

# in same way we can use  "   \t    "  for tab space
print("This is a tab:\tHello!")   

#so we can use escape sequences to format our strings in Python.